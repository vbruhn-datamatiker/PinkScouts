-- Setting up all tables for the Pink Scouts project:

-- 1. Master Table: USER
CREATE TABLE [USER] (
    UserId INT IDENTITY(1,1) NOT NULL,
    FirstName NVARCHAR(50) NOT NULL,
    LastName NVARCHAR(50) NOT NULL,
    IsLeader BIT NOT NULL DEFAULT 0,
    Email NVARCHAR(255) NOT NULL,
    [Password] NVARCHAR(255) NOT NULL,
    CONSTRAINT PK_USER PRIMARY KEY (UserId)
);

-- 2. Sub-entity Table: SCOUT (1:1 with USER)
CREATE TABLE SCOUT (
    UserId INT NOT NULL,
    Age INT NOT NULL,
    CONSTRAINT PK_SCOUT PRIMARY KEY (UserId),
    CONSTRAINT FK_SCOUT_USER FOREIGN KEY (UserId) REFERENCES [USER](UserId) ON DELETE CASCADE
);

-- 3. Lookup Table: SKILL
CREATE TABLE SKILL (
    SkillId INT IDENTITY(1,1) NOT NULL,
    SkillName NVARCHAR(100) NOT NULL,
    CONSTRAINT PK_SKILL PRIMARY KEY (SkillId)
);

-- 4. Junction Table: SCOUT_SKILL (M:N between SCOUT and SKILL)
CREATE TABLE SCOUT_SKILL (
    UserId INT NOT NULL,
    SkillId INT NOT NULL,
    SkillMastery INT NOT NULL,
    CONSTRAINT PK_SCOUT_SKILL PRIMARY KEY (UserId, SkillId),
    CONSTRAINT FK_SCOUT_SKILL_SCOUT FOREIGN KEY (UserId) REFERENCES SCOUT(UserId) ON DELETE CASCADE,
    CONSTRAINT FK_SCOUT_SKILL_SKILL FOREIGN KEY (SkillId) REFERENCES SKILL(SkillId) ON DELETE CASCADE
);

-- 5. Master Table: ACTIVITY
CREATE TABLE ACTIVITY (
    ActivityId INT IDENTITY(1,1) NOT NULL,
    ActivityName NVARCHAR(100) NOT NULL,
    [Description] NVARCHAR(MAX) NULL,
    CONSTRAINT PK_ACTIVITY PRIMARY KEY (ActivityId)
);

-- 6. Dependent Table: ACTIVITY_SCHEDULE (1:M with ACTIVITY)
CREATE TABLE ACTIVITY_SCHEDULE (
    ScheduleId INT IDENTITY(1,1) NOT NULL,
    ActivityId INT NOT NULL,
    [Start] DATETIME2 NOT NULL,
    [End] DATETIME2 NOT NULL,
    CONSTRAINT PK_ACTIVITY_SCHEDULE PRIMARY KEY (ScheduleId),
    CONSTRAINT FK_ACTIVITY_SCHEDULE_ACTIVITY FOREIGN KEY (ActivityId) REFERENCES ACTIVITY(ActivityId) ON DELETE CASCADE
);

-- 7. Junction Table: SCOUT_ACTIVITY (M:N between SCOUT and ACTIVITY_SCHEDULE)
CREATE TABLE SCOUT_ACTIVITY (
    UserId INT NOT NULL,
    ScheduleId INT NOT NULL,
    CONSTRAINT PK_SCOUT_ACTIVITY PRIMARY KEY (UserId, ScheduleId),
    CONSTRAINT FK_SCOUT_ACTIVITY_SCOUT FOREIGN KEY (UserId) REFERENCES SCOUT(UserId) ON DELETE CASCADE,
    CONSTRAINT FK_SCOUT_ACTIVITY_SCHEDULE FOREIGN KEY (ScheduleId) REFERENCES ACTIVITY_SCHEDULE(ScheduleId) ON DELETE NO ACTION
);
